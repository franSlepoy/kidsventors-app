export const PLAYER_LEVELS = [
  { level: 1, name: 'Aprendiz',     minXP: 0,    color: '#94a3b8', icon: '🌱' },
  { level: 2, name: 'Constructor',  minXP: 300,  color: '#38bdf8', icon: '🔧' },
  { level: 3, name: 'Inventor',     minXP: 800,  color: '#a78bfa', icon: '⚙️' },
  { level: 4, name: 'Ingeniero',    minXP: 1800, color: '#f59e0b', icon: '🚀' },
  { level: 5, name: 'Maestro',      minXP: 3500, color: '#ec4899', icon: '🏆' },
  { level: 6, name: 'Leyenda',      minXP: 6000, color: '#fbbf24', icon: '⭐' },
]

export function getPlayerLevel(totalXP) {
  let current = PLAYER_LEVELS[0]
  let next = PLAYER_LEVELS[1]
  for (let i = PLAYER_LEVELS.length - 1; i >= 0; i--) {
    if (totalXP >= PLAYER_LEVELS[i].minXP) {
      current = PLAYER_LEVELS[i]
      next = PLAYER_LEVELS[i + 1] || null
      break
    }
  }
  const xpInLevel = totalXP - current.minXP
  const xpToNext  = next ? next.minXP - current.minXP : 1
  const progress  = next ? Math.min(xpInLevel / xpToNext, 1) : 1
  return { current, next, progress, xpInLevel, xpToNext }
}

export function getNodeStatus(nodeId, completedNodes, allCompleted) {
  if (completedNodes.has(nodeId)) return 'completed'
  const node = ROBOTS[nodeId]
  if (!node) return 'locked'
  const prereqsMet = node.prerequisites.every(p => completedNodes.has(p))
  if (node.course === 'inicial' && prereqsMet) return 'available'
  if (node.course === 'intermedia') {
    const inicialCert = completedNodes.has('grab-croco')
    if (inicialCert && prereqsMet) return 'available'
  }
  return 'locked'
}
